"""Build worlds/obstacles.sdf: worlds/gusty.sdf (PX4 default world + WindEffects, calm unless agent/gz_wind.py
publishes) plus static poles and boxes from worlds/obstacles.json, the same table scenario.py checks clearance
against. gz is ENU (x east, y north); the table is PX4 NED from the spawn point at the world origin.

  python gen_obstacles.py            (run in worlds/)
"""
import json
import os
import xml.etree.ElementTree as ET

here = os.path.dirname(os.path.abspath(__file__))
tab = json.load(open(os.path.join(here, 'obstacles.json')))
t = ET.parse(os.path.join(here, 'gusty.sdf'))
w = t.getroot().find('world')
w.set('name', 'obstacles')
w.append(ET.Comment(' P13 obstacle course from worlds/obstacles.json (generated by gen_obstacles.py, do not edit) '))
for o in tab['obstacles']:
    m = ET.SubElement(w, 'model', {'name': o['name']})
    ET.SubElement(m, 'static').text = 'true'
    ET.SubElement(m, 'pose').text = f'{o["e"]} {o["n"]} {o["h"] / 2} 0 0 0'
    link = ET.SubElement(m, 'link', {'name': 'link'})
    for tag in ('collision', 'visual'):
        el = ET.SubElement(link, tag, {'name': tag})
        g = ET.SubElement(el, 'geometry')
        if o['kind'] == 'pole':
            c = ET.SubElement(g, 'cylinder')
            ET.SubElement(c, 'radius').text = str(o['r'])
            ET.SubElement(c, 'length').text = str(o['h'])
        else:
            ET.SubElement(ET.SubElement(g, 'box'), 'size').text = f'{o["de"]} {o["dn"]} {o["h"]}'
        if tag == 'visual':
            mat = ET.SubElement(el, 'material')
            for k in ('ambient', 'diffuse'):
                ET.SubElement(mat, k).text = '0.9 0.4 0.1 1'
ET.indent(t)
t.write(os.path.join(here, 'obstacles.sdf'), xml_declaration=True, encoding='UTF-8')
print(f'obstacles.sdf: {len(tab["obstacles"])} obstacles')
